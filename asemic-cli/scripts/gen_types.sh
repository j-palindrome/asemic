#!/usr/bin/env bash
# Regenerate every Rust -> Python codegen'd module (asemic_py/_wire.py, _keys.py, _schema.json,
# _types.py). Rust's golden tests emit the first three; datamodel-code-generator turns
# _schema.json into TypedDicts (dicts stay dicts at runtime: types are static-only).
# tests/test_codegen.py fails if _types.py was not regenerated from the current _schema.json.
set -euo pipefail
cd "$(dirname "$0")/.."
UPDATE_WIRE=1 cargo test -q -p asemic-schema --test gen_python_wire >/dev/null
UPDATE_WIRE=1 cargo test -q -p asemic-brain schema_golden >/dev/null
out=asemic_py/_types.py
sha=$(shasum -a 256 asemic_py/_schema.json | cut -d' ' -f1)
uvx --from datamodel-code-generator datamodel-codegen --input asemic_py/_schema.json \
  --input-file-type jsonschema --output-model-type typing.TypedDict --target-python-version 3.12 \
  --disable-timestamp --use-title-as-name --formatters builtin --output "$out" 2>/dev/null
{ printf '# generated by scripts/gen_types.sh from _schema.json sha256=%s; do not edit.\n' "$sha"; cat "$out"; } > "$out.tmp"
mv "$out.tmp" "$out"
echo "ok: $out"

# REPL verb table -> asemic_py/_api.pyi + _verbs.json (typed signatures & metadata for quickhelp & autocomplete)
cargo run -q --bin asemic-brain -- --verbs | python3 scripts/gen_api.py
