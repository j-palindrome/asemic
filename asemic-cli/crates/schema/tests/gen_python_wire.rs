//! Generates `asemic_py/_wire.py` from the wire-format constants in `src/{multi,wire}.rs` so the
//! two language sides can't silently drift (step 7 follow-up, 2026-10-10: replaces the old
//! grep-the-source-text Python test). Regenerate: `UPDATE_WIRE=1 cargo test -p asemic-schema`.
//! Plain `cargo test -p asemic-schema` fails if the checked-in file differs (golden-file check).

use std::path::PathBuf;

const P_FMT: &str = "<4sIIHH";
const F_FMT: &str = "<4sIHH";

fn python_module() -> String {
    let p_magic = std::str::from_utf8(asemic_schema::multi::MAGIC).unwrap();
    let f_magic = std::str::from_utf8(asemic_schema::wire::FRAME_MAGIC).unwrap();
    let t_magic = std::str::from_utf8(asemic_schema::wire::TEXT_MAGIC).unwrap();
    let p_len = asemic_schema::multi::HEAD_LEN;
    let f_len = asemic_schema::wire::FRAME_HEAD_LEN;

    format!(
        r#""""generated by asemic-schema; do not edit.

Regenerate: `UPDATE_WIRE=1 cargo test -p asemic-schema` (see crates/schema/tests/gen_python_wire.rs).

Points  `asemic/gen/<stream>`:  header struct {p_fmt:?} = magic, frame, n, dims, flags; then n*dims f32 LE.
Frame   `asemic/preview/<out>`:  header struct {f_fmt:?} = magic, frame, w, h; then w*h RGBA8.
Text    `asemic/preview/<ascii id>`:  same header, magic T_MAGIC; then h rows of w chars, UTF-8, newline-joined.
"""

from __future__ import annotations

import struct

P_MAGIC = b"{p_magic}"
F_MAGIC = b"{f_magic}"
T_MAGIC = b"{t_magic}"

P_HEAD = struct.Struct({p_fmt:?})
F_HEAD = struct.Struct({f_fmt:?})

assert P_HEAD.size == {p_len}, "P_HEAD size drifted from asemic-schema::multi::HEAD_LEN"
assert F_HEAD.size == {f_len}, "F_HEAD size drifted from asemic-schema::wire::FRAME_HEAD_LEN"
"#,
        p_fmt = P_FMT,
        f_fmt = F_FMT,
        p_magic = p_magic,
        f_magic = f_magic,
        t_magic = t_magic,
        p_len = p_len,
        f_len = f_len,
    )
}

/// Written-path cases `asemic_py.columns.resolve_path` must agree with: Rust computes the
/// expected outputs here, so the Python mirror is checked against the canonical resolver.
const RESOLVE_INPUTS: &[(&str, &str)] = &[
    ("main", "gain"), ("drawing", "ink"), ("drawing", "drawing/word"), ("drawing", "./drawing/word"),
    ("drawing", "/drawing/drawing/word"), ("drawing", "../controls/gain.value"),
    ("controls", "noise/chaos_lfo:x"), ("controls/noise", "../arena.x"), ("drawing", "asemic/io/osc/x"),
    ("a/b", "../../c"), ("a", "/x/y:vx"),
];

fn keys_module() -> String {
    use asemic_schema::{ids, keys};
    let spaces: String = keys::SPACES.iter()
        .map(|(n, pat, pre, suf)| format!("    ({n:?}, {pat:?}, {pre:?}, {suf:?}),\n"))
        .collect();
    let cases: String = RESOLVE_INPUTS.iter()
        .map(|(l, r)| format!("    ({l:?}, {r:?}, {:?}),\n", ids::resolve(&ids::scope(Some(l)), r)))
        .collect();
    format!(
        r#""""generated by asemic-schema; do not edit.

Regenerate: `UPDATE_WIRE=1 cargo test -p asemic-schema` (see crates/schema/tests/gen_python_wire.rs).
Brain-state keyspaces (`asemic_schema::keys::SPACES`) mirrored by `asemic_py/state.py`, and
`ids::resolve` golden cases the Python `resolve_path` mirror is tested against.
"""

from __future__ import annotations

STATE = {state:?}
COMPONENT_PREFIX = {comp:?}
PARAM_PREFIX = {param:?}
ROUTE_PREFIX = {route:?}
TEX_PREFIX = {tex:?}
BRAIN_READY = {ready:?}

# (name, subscribe pattern, prefix, suffix): id = key minus prefix/suffix; "" prefix = singleton
SPACES: tuple[tuple[str, str, str, str], ...] = (
{spaces})

# (block label, written ref, canonical id) from `ids::resolve`
RESOLVE_CASES: tuple[tuple[str, str, str], ...] = (
{cases})
"#,
        state = keys::STATE, comp = keys::COMPONENT_PREFIX, param = keys::PARAM_PREFIX,
        route = keys::ROUTE_PREFIX, tex = keys::TEX_PREFIX, ready = keys::BRAIN_READY,
    )
}

pub fn py_path(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../asemic_py").join(name)
}

#[test]
fn python_wire_module_matches_schema() {
    golden(py_path("_wire.py"), python_module());
}

#[test]
fn python_keys_module_matches_schema() {
    golden(py_path("_keys.py"), keys_module());
}

pub fn golden(path: PathBuf, generated: String) {
    if std::env::var("UPDATE_WIRE").is_ok() {
        std::fs::write(&path, &generated).expect("write generated module");
        return;
    }

    let on_disk = std::fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "{} missing or unreadable ({e}); run `UPDATE_WIRE=1 cargo test -p asemic-schema` to generate it",
            path.display()
        )
    });
    assert_eq!(
        on_disk, generated,
        "{} is stale; regenerate with `UPDATE_WIRE=1 cargo test -p asemic-schema`",
        path.display()
    );
}
